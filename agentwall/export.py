"""Hard enforcement exports.

Environment proxies are cooperative: code that ignores HTTPS_PROXY can go
around them. For real containment, put the agent on a network whose only way
out is agentwall. These exporters generate that setup.
"""
from __future__ import annotations

from .policy import Policy


def compose(policy: Policy, segment: str, image: str) -> str:
    seg = policy.segments[segment]
    cred = f"{seg.name}:{seg.token}" if seg.token else seg.name
    return f"""# Generated by `agentwall export compose`.
# The agent sits on an `internal` network with NO route to the internet.
# Its only way out is the agentwall container, which enforces the policy.
services:
  agentwall:
    build: .
    command: ["agentwall", "-p", "/policy/agentwall.toml", "up"]
    environment:
      AGENTWALL_API_KEY: ${{AGENTWALL_API_KEY}}  # provider key, stays in this container only
    volumes:
      - ./agentwall.toml:/policy/agentwall.toml:ro
      - ./logs:/logs
    networks: [agents, egress]

  agent:
    image: {image}
    command: ["sleep", "infinity"]  # replace with your agent
    environment:
      HTTPS_PROXY: http://{cred}@agentwall:8899
      HTTP_PROXY: http://{cred}@agentwall:8899
      NO_PROXY: agentwall
      OPENAI_BASE_URL: http://agentwall:8898/v1
      OPENAI_API_KEY: "{cred}"
    volumes:
      - ./workspace:/workspace
    working_dir: /workspace
    networks: [agents]
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    read_only: true
    tmpfs: [/tmp]

networks:
  agents:
    internal: true   # no internet, no host LAN
  egress: {{}}

# In agentwall.toml for this setup use:
#   [defaults]
#   proxy_listen = "0.0.0.0:8899"
#   gateway_listen = "0.0.0.0:8898"
#   log_path = "/logs/agentwall.log.jsonl"
"""


def cilium(policy: Policy) -> str:
    """CiliumNetworkPolicy per segment: pods labelled agentwall/segment=<name>
    may only reach the FQDNs in their egress list (plus DNS)."""
    docs = []
    for seg in policy.segments.values():
        fqdns = []
        ports = set()
        for rule in seg.egress:
            host, sep, port = rule.rpartition(":")
            if not sep or not port.isdigit():
                host, port = rule, ""
            key = "matchPattern" if "*" in host else "matchName"
            fqdns.append(f"            - {key}: \"{host}\"")
            ports.update([port] if port else ["443", "80"])
        port_lines = "\n".join(f'            - port: "{p}"\n              protocol: TCP' for p in sorted(ports)) or '            - port: "443"\n              protocol: TCP'
        fqdn_block = "\n".join(fqdns) or '            - matchName: "none.invalid"'
        docs.append(f"""apiVersion: cilium.io/v2
kind: CiliumNetworkPolicy
metadata:
  name: agentwall-{seg.name}
spec:
  description: "agentwall segment {seg.name}: default-deny egress"
  endpointSelector:
    matchLabels:
      agentwall/segment: {seg.name}
  egress:
    - toEndpoints:
        - matchLabels:
            k8s:io.kubernetes.pod.namespace: kube-system
            k8s-app: kube-dns
      toPorts:
        - ports:
            - port: "53"
              protocol: ANY
          rules:
            dns:
              - matchPattern: "*"
    - toFQDNs:
{fqdn_block}
      toPorts:
        - ports:
{port_lines}
""")
    return "---\n".join(docs)
